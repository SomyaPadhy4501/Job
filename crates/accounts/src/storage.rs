//! Where resume files live. Chosen explicitly with `STORAGE_DRIVER`:
//!
//! - `r2`: a private Cloudflare R2 bucket (`R2_ACCOUNT_ID`, `R2_ACCESS_KEY_ID`,
//!   `R2_SECRET_ACCESS_KEY`, `R2_BUCKET`; `R2_ENDPOINT` overrides the endpoint
//!   for an S3-compatible test server).
//! - `s3`: any other S3-compatible private bucket, such as Backblaze B2
//!   (`S3_ENDPOINT` like `https://s3.us-west-004.backblazeb2.com`,
//!   `S3_REGION` like `us-west-004`, `S3_BUCKET`, `S3_ACCESS_KEY_ID`,
//!   `S3_SECRET_ACCESS_KEY`).
//!
//! For both, requests are signed here and sent from here: no signed URL ever
//! reaches a browser.
//! - `fs`: a local folder (`STORAGE_FS_ROOT`, default `data/blobs`) for
//!   development and tests. Refused on Vercel, whose disk is temporary.
//!
//! Anything else, or a missing setting, disables uploads (503) without
//! affecting the rest of the API.

use std::path::{Path, PathBuf};
use std::time::Duration;

use rusty_s3::{Bucket, Credentials, S3Action, UrlStyle};

/// Files are at most 4 MB; refuse to read more back than this.
const MAX_OBJECT_BYTES: usize = 5 * 1024 * 1024;
const SIGNATURE_TTL: Duration = Duration::from_secs(60);

#[derive(Debug, thiserror::Error)]
pub enum StorageError {
    #[error("file storage isn't configured: {0}")]
    Disabled(String),
    #[error("file not found")]
    NotFound,
    #[error("invalid object key")]
    BadKey,
    #[error("file storage failed: {0}")]
    Backend(String),
}

pub enum Storage {
    R2(Box<R2Store>),
    Fs(FsStore),
    Disabled(String),
}

impl Storage {
    pub fn from_env() -> Self {
        let on_vercel = std::env::var_os("VERCEL").is_some();
        match std::env::var("STORAGE_DRIVER")
            .ok()
            .as_deref()
            .map(str::trim)
        {
            Some("r2") => match R2Store::from_env() {
                Ok(store) => Storage::R2(Box::new(store)),
                Err(why) => Storage::Disabled(why),
            },
            Some("s3") => match R2Store::from_s3_env() {
                Ok(store) => Storage::R2(Box::new(store)),
                Err(why) => Storage::Disabled(why),
            },
            Some("fs") if on_vercel => {
                Storage::Disabled("STORAGE_DRIVER=fs isn't allowed on Vercel".into())
            }
            Some("fs") => {
                let root = std::env::var("STORAGE_FS_ROOT").unwrap_or_else(|_| "data/blobs".into());
                Storage::Fs(FsStore::new(root))
            }
            Some(other) => Storage::Disabled(format!(
                "unknown STORAGE_DRIVER {other:?}; use r2, s3 or fs"
            )),
            None => Storage::Disabled("STORAGE_DRIVER isn't set".into()),
        }
    }

    pub fn is_enabled(&self) -> bool {
        !matches!(self, Storage::Disabled(_))
    }

    pub fn driver(&self) -> &'static str {
        match self {
            Storage::R2(s) => s.driver,
            Storage::Fs(_) => "fs",
            Storage::Disabled(_) => "disabled",
        }
    }

    pub async fn put(
        &self,
        key: &str,
        bytes: Vec<u8>,
        content_type: &str,
    ) -> Result<(), StorageError> {
        check_key(key)?;
        match self {
            Storage::R2(s) => s.put(key, bytes, content_type).await,
            Storage::Fs(s) => s.put(key, &bytes).await,
            Storage::Disabled(why) => Err(StorageError::Disabled(why.clone())),
        }
    }

    pub async fn get(&self, key: &str) -> Result<Vec<u8>, StorageError> {
        check_key(key)?;
        match self {
            Storage::R2(s) => s.get(key).await,
            Storage::Fs(s) => s.get(key).await,
            Storage::Disabled(why) => Err(StorageError::Disabled(why.clone())),
        }
    }

    /// Deleting something that is already gone succeeds.
    pub async fn delete(&self, key: &str) -> Result<(), StorageError> {
        check_key(key)?;
        match self {
            Storage::R2(s) => s.delete(key).await,
            Storage::Fs(s) => s.delete(key).await,
            Storage::Disabled(why) => Err(StorageError::Disabled(why.clone())),
        }
    }
}

/// Keys are generated by the API (`resumes/<user id>/<uuid>`), never taken
/// from a request; this is a second line of defence for the folder driver.
pub fn check_key(key: &str) -> Result<(), StorageError> {
    let ok = !key.is_empty()
        && key.len() <= 200
        && !key.starts_with('/')
        && key
            .split('/')
            .all(|part| !part.is_empty() && part != "." && part != "..")
        && key
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'/' | b'-' | b'_' | b'.'));
    if ok {
        Ok(())
    } else {
        Err(StorageError::BadKey)
    }
}

pub struct FsStore {
    root: PathBuf,
}

impl FsStore {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self { root: root.into() }
    }

    fn path(&self, key: &str) -> PathBuf {
        self.root.join(Path::new(key))
    }

    async fn put(&self, key: &str, bytes: &[u8]) -> Result<(), StorageError> {
        let path = self.path(key);
        if let Some(parent) = path.parent() {
            tokio::fs::create_dir_all(parent).await.map_err(io)?;
        }
        // Write then rename, so a reader never sees half a file.
        let tmp = path.with_extension(format!(
            "tmp-{}",
            crate::token::hex(&crate::token::random_bytes::<6>())
        ));
        tokio::fs::write(&tmp, bytes).await.map_err(io)?;
        tokio::fs::rename(&tmp, &path).await.map_err(io)
    }

    async fn get(&self, key: &str) -> Result<Vec<u8>, StorageError> {
        match tokio::fs::read(self.path(key)).await {
            Ok(bytes) => Ok(bytes),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Err(StorageError::NotFound),
            Err(e) => Err(io(e)),
        }
    }

    async fn delete(&self, key: &str) -> Result<(), StorageError> {
        match tokio::fs::remove_file(self.path(key)).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(io(e)),
        }
    }
}

fn io(e: std::io::Error) -> StorageError {
    StorageError::Backend(e.to_string())
}

/// An S3-compatible bucket: Cloudflare R2 (`r2`) or any other (`s3`).
pub struct R2Store {
    driver: &'static str,
    bucket: Bucket,
    credentials: Credentials,
    http: reqwest::Client,
}

impl R2Store {
    pub fn from_env() -> Result<Self, String> {
        let var = |name: &str| {
            std::env::var(name)
                .ok()
                .map(|v| v.trim().to_owned())
                .filter(|v| !v.is_empty())
        };
        let missing: Vec<&str> = ["R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_BUCKET"]
            .into_iter()
            .filter(|n| var(n).is_none())
            .collect();
        if !missing.is_empty() {
            return Err(format!("missing {}", missing.join(", ")));
        }
        let endpoint = match (var("R2_ENDPOINT"), var("R2_ACCOUNT_ID")) {
            (Some(endpoint), _) => endpoint,
            (None, Some(account)) => format!("https://{account}.r2.cloudflarestorage.com"),
            (None, None) => return Err("missing R2_ACCOUNT_ID (or R2_ENDPOINT)".into()),
        };
        Self::new(
            &endpoint,
            &var("R2_BUCKET").unwrap(),
            &var("R2_ACCESS_KEY_ID").unwrap(),
            &var("R2_SECRET_ACCESS_KEY").unwrap(),
        )
    }

    /// `STORAGE_DRIVER=s3`: Backblaze B2 or another S3-compatible service.
    pub fn from_s3_env() -> Result<Self, String> {
        let var = |name: &str| {
            std::env::var(name)
                .ok()
                .map(|v| v.trim().to_owned())
                .filter(|v| !v.is_empty())
        };
        let names = [
            "S3_ENDPOINT",
            "S3_REGION",
            "S3_BUCKET",
            "S3_ACCESS_KEY_ID",
            "S3_SECRET_ACCESS_KEY",
        ];
        let missing: Vec<&str> = names.into_iter().filter(|n| var(n).is_none()).collect();
        if !missing.is_empty() {
            return Err(format!("missing {}", missing.join(", ")));
        }
        let endpoint = var("S3_ENDPOINT").unwrap();
        if !endpoint.starts_with("https://") {
            return Err("S3_ENDPOINT must start with https://".into());
        }
        let mut store = Self::with_region(
            &endpoint,
            &var("S3_BUCKET").unwrap(),
            &var("S3_ACCESS_KEY_ID").unwrap(),
            &var("S3_SECRET_ACCESS_KEY").unwrap(),
            &var("S3_REGION").unwrap(),
        )?;
        store.driver = "s3";
        Ok(store)
    }

    pub fn new(endpoint: &str, bucket: &str, key_id: &str, secret: &str) -> Result<Self, String> {
        Self::with_region(endpoint, bucket, key_id, secret, "auto")
    }

    /// `region` is what requests are signed for: `auto` on R2, the bucket's
    /// region elsewhere (e.g. `us-west-004` on Backblaze B2).
    pub fn with_region(
        endpoint: &str,
        bucket: &str,
        key_id: &str,
        secret: &str,
        region: &str,
    ) -> Result<Self, String> {
        let url = endpoint
            .parse()
            .map_err(|e| format!("bad storage endpoint: {e}"))?;
        let bucket = Bucket::new(url, UrlStyle::Path, bucket.to_owned(), region.to_owned())
            .map_err(|e| format!("bad storage bucket: {e}"))?;
        let http = reqwest::Client::builder()
            .timeout(Duration::from_secs(20))
            .build()
            .map_err(|e| e.to_string())?;
        Ok(Self {
            driver: "r2",
            bucket,
            credentials: Credentials::new(key_id, secret),
            http,
        })
    }

    async fn put(&self, key: &str, bytes: Vec<u8>, content_type: &str) -> Result<(), StorageError> {
        let url = self
            .bucket
            .put_object(Some(&self.credentials), key)
            .sign(SIGNATURE_TTL);
        let res = self
            .http
            .put(url)
            .header(reqwest::header::CONTENT_TYPE, content_type)
            .body(bytes)
            .send()
            .await
            .map_err(backend)?;
        check_status(res.status())
    }

    async fn get(&self, key: &str) -> Result<Vec<u8>, StorageError> {
        let url = self
            .bucket
            .get_object(Some(&self.credentials), key)
            .sign(SIGNATURE_TTL);
        let mut res = self.http.get(url).send().await.map_err(backend)?;
        if res.status() == reqwest::StatusCode::NOT_FOUND {
            return Err(StorageError::NotFound);
        }
        check_status(res.status())?;
        let mut body = Vec::new();
        while let Some(chunk) = res.chunk().await.map_err(backend)? {
            if body.len() + chunk.len() > MAX_OBJECT_BYTES {
                return Err(StorageError::Backend(
                    "object is larger than any upload".into(),
                ));
            }
            body.extend_from_slice(&chunk);
        }
        Ok(body)
    }

    async fn delete(&self, key: &str) -> Result<(), StorageError> {
        let url = self
            .bucket
            .delete_object(Some(&self.credentials), key)
            .sign(SIGNATURE_TTL);
        let res = self.http.delete(url).send().await.map_err(backend)?;
        if res.status() == reqwest::StatusCode::NOT_FOUND {
            return Ok(());
        }
        check_status(res.status())
    }
}

fn backend(e: reqwest::Error) -> StorageError {
    // Without the URL: it carries a signature.
    StorageError::Backend(e.without_url().to_string())
}

fn check_status(status: reqwest::StatusCode) -> Result<(), StorageError> {
    if status.is_success() {
        Ok(())
    } else {
        Err(StorageError::Backend(format!("storage answered {status}")))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_checked() {
        assert!(check_key("resumes/5c1e/9f2a-1b").is_ok());
        for bad in [
            "",
            "/abs",
            "a/../b",
            "a//b",
            "a/./b",
            "sp ace",
            "semi;colon",
            "dots/..",
        ] {
            assert!(check_key(bad).is_err(), "{bad:?}");
        }
    }

    #[tokio::test]
    async fn folder_driver_round_trips() {
        let dir = std::env::temp_dir().join(format!("jobboard-test-{}", uuid::Uuid::new_v4()));
        let store = Storage::Fs(FsStore::new(&dir));
        store
            .put("resumes/u/f", b"%PDF-".to_vec(), "application/pdf")
            .await
            .unwrap();
        assert_eq!(store.get("resumes/u/f").await.unwrap(), b"%PDF-");
        store.delete("resumes/u/f").await.unwrap();
        assert!(matches!(
            store.get("resumes/u/f").await,
            Err(StorageError::NotFound)
        ));
        store.delete("resumes/u/f").await.unwrap(); // already gone
        assert!(matches!(
            store.put("../escape", vec![1], "x").await,
            Err(StorageError::BadKey)
        ));
        let _ = std::fs::remove_dir_all(dir);
    }

    #[tokio::test]
    async fn disabled_storage_fails_closed() {
        let store = Storage::Disabled("STORAGE_DRIVER isn't set".into());
        assert!(!store.is_enabled());
        assert!(matches!(
            store.put("k", vec![], "x").await,
            Err(StorageError::Disabled(_))
        ));
    }

    #[test]
    fn r2_signs_requests_locally() {
        let store = R2Store::new(
            "https://acct.r2.cloudflarestorage.com",
            "resumes",
            "id",
            "secret",
        )
        .unwrap();
        let url = store
            .bucket
            .get_object(Some(&store.credentials), "resumes/u/f")
            .sign(SIGNATURE_TTL);
        assert_eq!(url.host_str(), Some("acct.r2.cloudflarestorage.com"));
        assert!(url.path().starts_with("/resumes/resumes/u/f"));
        assert!(url.query().unwrap().contains("X-Amz-Signature="));
    }

    #[test]
    fn s3_compatible_buckets_sign_for_their_region() {
        let mut store = R2Store::with_region(
            "https://s3.us-west-004.backblazeb2.com",
            "job-board-resumes",
            "keyid",
            "secret",
            "us-west-004",
        )
        .unwrap();
        store.driver = "s3";
        let url = store
            .bucket
            .put_object(Some(&store.credentials), "resumes/u/f")
            .sign(SIGNATURE_TTL);
        assert_eq!(url.host_str(), Some("s3.us-west-004.backblazeb2.com"));
        assert!(url.path().starts_with("/job-board-resumes/resumes/u/f"));
        let query = url.query().unwrap();
        assert!(query.contains("us-west-004%2Fs3%2Faws4_request"), "{query}");
        assert_eq!(Storage::R2(Box::new(store)).driver(), "s3");
    }
}
